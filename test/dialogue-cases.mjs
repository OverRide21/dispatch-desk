// Original fictional calls. Each scenario has five natural variants per language.
const marathi = 'mr-IN';
const hindi = 'hi-IN';

function scenario(id, mr, hi, expected, { setup, finish, mid } = {}) {
  return [mr, hi].flatMap((lines, index) => lines.map((utterance, variant) => {
    const language = index === 0 ? marathi : hindi;
    const before = setup?.[index] ?? [];
    const after = finish?.[index] ?? [];
    return { id: `${id}/${language}/${variant + 1}`, language, before, utterance, after, expected, mid };
  }));
}

